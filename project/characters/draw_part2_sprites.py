# ---- carry over wizard + crows from the current data file (source of truth)
js = ("const fs=require('fs');const src=fs.readFileSync('../game/sprites-data.js','utf8');"
      "const fn=new Function(src+';return {SPRITES,WIZ_PAL}');"
      "process.stdout.write(JSON.stringify(fn()))")
old = json.loads(subprocess.run(['node', '-e', js], capture_output=True, text=True, check=True).stdout)
WIZ_PAL = old['WIZ_PAL']
CARRY = {k: old['SPRITES'][k] for k in ('wizardA', 'wizardB', 'crowA', 'crowB')}

CAST = {}
CAST.update(sprites_lane1.SPRITES)
CAST.update(sprites_lane2.SPRITES)
CAST.update(sprites_lane3.SPRITES)
PUNCH = sprites_lane3.PUNCH

def mirror(rows):
    return [r[::-1] for r in rows]

SKIN = set('sSH')
def derive_walk(rows):
    """Study §4.1: left boot steps 1px down, right boot lifts 1px; the hand on
    the back-foot side drops 1px, the other rises. Bob is the engine's job."""
    w = [list(r) for r in rows]
    feet = {'L': [], 'R': []}
    for y in range(21, 24):
        for x, ch in enumerate(w[y]):
            if ch != '.':
                feet['L' if x < 8 else 'R'].append((x, y, ch))
    def shift(cluster, dy, ymin, ymax):
        for (x, y, ch) in cluster: w[y][x] = '.'
        for (x, y, ch) in cluster:
            ny = min(ymax, max(ymin, y + dy))
            if w[ny][x] == '.': w[ny][x] = ch
            else: w[y][x] = ch
    if feet['L'] and feet['R']:
        shift(feet['L'], +1, 20, 23)
        shift(feet['R'], -1, 20, 23)
    for side, dy in (('L', -1), ('R', +1)):
        pts = [(x, y, w[y][x]) for y in range(12, 19) for x in range(16)
               if w[y][x] in SKIN and ((x < 8) == (side == 'L')) and (x <= 3 or x >= 12)]
        if pts:
            ymax = max(p[1] for p in pts)
            hand = [p for p in pts if p[1] >= ymax - 1]
            shift(hand, dy, 11, 18)
    return [''.join(r) for r in w]

# ---- assemble the full data set
DATA = {}
for name, views in CAST.items():
    pal = KING_PAL if name == 'king' else PAL
    DATA[name + '_down'] = views['down']
    DATA[name + '_up'] = views['up']
    DATA[name + '_right'] = views['right']
    DATA[name + '_left'] = mirror(views['right'])
    for d in ('down', 'up', 'right', 'left'):
        DATA[name + '_' + d + '_w'] = derive_walk(DATA[name + '_' + d])
for k, frames in PUNCH.items():
    for tag, fr in zip(('pa', 'px', 'pr'), frames):
        DATA['cornman_' + tag + '_' + k] = fr
for tag, fr in zip(('pa', 'px', 'pr'), PUNCH['right_r']):
    DATA['cornman_' + tag + '_left_r'] = mirror(fr)
DATA.update(CARRY)

# ---- validate everything
ok = True
for name, rows in DATA.items():
    pal = KING_PAL if name.startswith('king') else (WIZ_PAL if name.startswith('wizard') else PAL)
    h = 16 if name.startswith('crow') else 32 if name.startswith('wizard') else 24
    wdt = 24 if name.startswith('wizard') else 16
    if len(rows) != h: print(f'{name}: {len(rows)} rows != {h}'); ok = False
    for i, r in enumerate(rows):
        if len(r) != wdt: print(f'{name} row {i}: width {len(r)} != {wdt}'); ok = False
        bad = set(r) - set(pal) - {'.'}
        if bad: print(f'{name} row {i}: stray {bad}'); ok = False
print('VALID' if ok else 'FIX NEEDED')
if not ok: sys.exit(1)

