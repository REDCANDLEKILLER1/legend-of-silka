js.append('const STATUE_PAL = ' + json.dumps(STATUE_PAL) + ';')
js.append('const WIZ_PAL = ' + json.dumps(WIZ_PAL) + ';')
js.append('const SPRITES = {')
items = list(DATA.items())
for i, (name, rows) in enumerate(items):
    js.append(f'  {name}: ' + json.dumps(rows) + (',' if i < len(items) - 1 else ''))
js.append('};')
open('../game/sprites-data.js', 'w').write('\n'.join(js) + '\n')
print('wrote game/sprites-data.js with', len(DATA), 'sprites')

# ---- lineup sheets for Michael's gate
import os
os.makedirs('lineup-v2', exist_ok=True)
def draw_sprite(img, rows, pal, ox, oy, sc, fill=None):
    for y, row in enumerate(rows):
        for x, ch in enumerate(row):
            if ch == '.': continue
            c = fill or pal[ch]
            rgb = tuple(int(c[i:i+2], 16) for i in (1, 3, 5))
            img.paste(rgb, (ox + x * sc, oy + y * sc, ox + x * sc + sc, oy + y * sc + sc))

